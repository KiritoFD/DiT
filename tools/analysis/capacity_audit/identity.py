"""Check archived PNG identity by sample ID, never JSONL line position."""
import argparse
import json
from pathlib import Path
import sys
from types import SimpleNamespace
import numpy as np
from PIL import Image
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
from tools.analysis.capacity_audit.common import rows, sha, write
from src.eval.in_mem_eval import _get_cache


def audit(run, csv_path, output):
    run = Path(run); output = Path(output); output.mkdir(parents=True, exist_ok=False)
    data = rows(csv_path)
    cfg = json.loads((run/'resolved_config.json').read_text(encoding='utf-8'))
    cache = _get_cache(csv_path, len(data), None, '', SimpleNamespace(**cfg))
    report = {'run': str(run), 'csv_sha256': sha(csv_path), 'steps': {}}
    for folder in sorted((run/'eval_samples_ctrl').glob('step*/eval200fix')):
        samples = [json.loads(x) for x in (folder/'samples.jsonl').read_text(encoding='utf-8').splitlines()]
        by_id = {s['sample_id']: s for s in samples}
        assert len(samples) == len(by_id) == len(data)
        done = json.loads((folder/'DONE.json').read_text(encoding='utf-8'))
        ordered = []
        for i, row in enumerate(data):
            sample = by_id[str(row['img_id'])]
            for field, col in [('writer_id','calligrapher_id'), ('script_id','script_id'),
                               ('char_id','character_id')]:
                assert int(sample[field]) == int(row[col]), (i, field)
            assert str(sample['glyph_key']) == str(row['glyph_id'])
            expected = ((cache['gts'][i]+1)*127.5).byte().permute(1,2,0).numpy()
            actual = np.array(Image.open(folder/f'gt{i}.png').convert('RGB'))
            assert np.array_equal(expected, actual), ('GT mismatch', i)
            g = ((1-cache['skels_latent'][i,0])*255).byte().numpy()
            saved = run/'eval_samples_ctrl/eval200fix_input_g'/f'g{i}.png'
            assert np.array_equal(g, np.array(Image.open(saved).convert('L'))), ('STD mismatch', i)
            digest = sha(folder/f'g{i}.png')
            assert done['artifacts'][f'png:g{i}.png'] == digest, ('DONE mismatch', i)
            ordered.append({'index': i, 'png': f'g{i}.png', 'png_sha256': digest,
                            'sample_id': row['img_id'], 'character': row['character'],
                            'writer': row['calligrapher'], 'script': row['script'],
                            'condition_ids': cache['conds'][i],
                            'hier_ids': [a[i] for a in cache['hier_conds']]})
        step = folder.parent.name
        write(output/f'{step}_ordered.json', ordered)
        report['steps'][step] = {'n': len(ordered), 'all_metadata_gt_std_done_match': True,
                                 'protocol': json.loads((folder/'protocol.json').read_text(encoding='utf-8'))}
    report['limitations'] = ['samples.jsonl is sorted by sample_id, not PNG index.',
        'Archives verify identity/STD, not historical in-memory labels or exact sampler execution.',
        'No image was relabelled or regenerated by this audit.']
    write(output/'report.json', report)
    print(json.dumps(report, ensure_ascii=False), flush=True)


def replay(checkpoint, run, csv_path, output):
    """Small deterministic generation replay; does not rewrite archived PNGs."""
    import gc
    import torch
    from src.eval.model_io import load_model_from_ckpt
    from src.eval.sampler import sample_latents, build_diffusion
    from src.loss import flow_kwargs_from
    from src.utils.vae_scaling import resolve_vae_scaling
    from src.eval.metrics import ssim
    torch.set_num_threads(4);torch.set_grad_enabled(False)
    torch.cuda.set_per_process_memory_fraction(.075)
    output=Path(output);output.mkdir(parents=True,exist_ok=False)
    model,args=load_model_from_ckpt(checkpoint,device='cuda',use_ema=True)
    cache=_get_cache(csv_path,187,None,'',args)
    indices=[75,82,158,133,99,140,154,178]
    diff=build_diffusion(50,'flow',flow_kwargs=flow_kwargs_from(args))
    lat=sample_latents(model,diff,cache['noise'][indices],
        [cache['conds'][i] for i in indices],1.,2,'cuda',
        skel=cache['skels_latent'][indices],seed=0,
        hier_conds=tuple([axis[i] for i in indices] for axis in cache['hier_conds']))
    del model;gc.collect();torch.cuda.empty_cache()
    from diffusers import AutoencoderKL
    vae=AutoencoderKL.from_pretrained(args.vae_path).cuda().eval()
    sf,shift=resolve_vae_scaling(args);record=[]
    for j,i in enumerate(indices):
        pred=vae.decode(lat[j:j+1].cuda()/sf+shift).sample[0].clamp(-1,1)
        rgb=((pred.cpu().permute(1,2,0)+1)*127.5).byte().numpy()
        Image.fromarray(rgb).save(output/f'g{i}.png')
        old=np.array(Image.open(Path(run)/f'g{i}.png').convert('RGB'))
        record.append({'index':i,'pixel_mae':float(np.abs(rgb.astype(float)-old).mean()/255),
                       'ssim_vs_archive':ssim(rgb/255.,old/255.),
                       'archived_sha256':sha(Path(run)/f'g{i}.png')})
    write(output/'replay.json',{'checkpoint_sha256':sha(checkpoint),'indices':indices,'records':record,
        'limitations':['B2 eager replay vs historical compiled/batch sampling; not a bitwise parity test.']})
    print(record,flush=True)


if __name__ == '__main__':
    p=argparse.ArgumentParser();p.add_argument('--run',required=True)
    p.add_argument('--csv',default='exp-std/csv/eval200_fixed.csv');p.add_argument('--out',required=True)
    p.add_argument('--replay-checkpoint',default='')
    a=p.parse_args()
    if a.replay_checkpoint: replay(a.replay_checkpoint,a.run,a.csv,a.out)
    else: audit(a.run,a.csv,a.out)
